#!/usr/bin/env python3
"""Build the benchmarking archive for the Zenodo deposit.

The benchmark outputs are not repository content: they are large, they are
regenerated by every rebuild, and they are evidence for a paper rather than
code. They are deposited instead, in their own archive, separate from the
reference data, because the two are versioned and cited for different reasons
-- the reference set decides what a call is, the benchmark outputs record how
well those calls did.

What is deliberately NOT in here: `validation/results_rivm.csv`, the
Norovirus Typing Tool's own export. `validation/README.md` states it is not
redistributed by this project; obtain it upstream or regenerate it from the
typing tool. Everything here is output this project produced, including the
comparison tables derived from that file, which are ours.

    python scripts/build_benchmark_archive.py --out-dir zenodo [--apply]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"

# Never deposit these, whatever happens to be on disk. The first is the
# comparator's raw export; the rest are caches and scratch.
EXCLUDE_NAMES = {"results_rivm.csv", "rivm_calls.csv"}
EXCLUDE_SUFFIX = {".pyc", ".log.lock"}
EXCLUDE_DIRS = {"__pycache__", ".cache", ".ipynb_checkpoints"}


def members():
    """Every file to deposit, relative to results/, sorted for a stable archive."""
    out = []
    for f in sorted(RESULTS.rglob("*")):
        if not f.is_file():
            continue
        if f.name in EXCLUDE_NAMES or f.suffix in EXCLUDE_SUFFIX:
            continue
        if EXCLUDE_DIRS & set(f.relative_to(RESULTS).parts):
            continue
        out.append(f.relative_to(RESULTS))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out-dir", default="zenodo")
    ap.add_argument("--version", default=None,
                    help="defaults to the reference set version, so the two line up")
    ap.add_argument("--apply", action="store_true", help="write the archive")
    a = ap.parse_args()

    if not RESULTS.exists():
        sys.exit(f"missing {RESULTS}")
    version = a.version or json.loads(
        (ROOT / "calicityper" / "data" / "reference_manifest.json").read_text()
    )["reference_set_version"]

    files = members()
    by_top = {}
    for f in files:
        by_top.setdefault(f.parts[0] if len(f.parts) > 1 else "(top level)", []).append(f)
    total = sum((RESULTS / f).stat().st_size for f in files)
    print(f"benchmarking archive version {version}")
    print(f"{len(files)} files, {total / 1e6:.1f} MB over {len(by_top)} entries:")
    for top, fs in sorted(by_top.items()):
        print(f"  {top:34s} {len(fs):4d} files")

    skipped = [f for f in sorted(RESULTS.rglob("*"))
               if f.is_file() and f.relative_to(RESULTS) not in set(files)]
    if skipped:
        print(f"\nexcluded ({len(skipped)}):")
        for f in skipped[:10]:
            print(f"  {f.relative_to(RESULTS)}")

    out_dir = Path(a.out_dir)
    archive = out_dir / f"benchmarking-datasets-{version}.tar.gz"
    if not a.apply:
        print(f"\ndry run; would write {archive}\npass --apply to build")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive, "w:gz") as tar:
        for f in files:
            tar.add(RESULTS / f, arcname=str(Path("benchmarking") / f))
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    print(f"\nwrote {archive} ({archive.stat().st_size / 1e6:.1f} MB)")
    print(f"sha256 {digest}")

    with tarfile.open(archive) as tar:
        names = tar.getnames()
    bad = [n for n in names if Path(n).name in EXCLUDE_NAMES]
    if bad:
        sys.exit(f"the archive contains data this project does not redistribute: {bad}")
    print(f"re-checked: {len(names)} members, none of them the comparator's raw calls")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
